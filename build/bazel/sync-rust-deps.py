#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["typer==0.19.2"]
# ///
"""Export locked registry dependencies without changing any Cargo manifest.

Cargo is used only for metadata discovery. Bazel compiles each local crate
independently; local path dependencies never pass through crate_universe.
"""

import json
import subprocess
from pathlib import Path
from typing import Annotated

import typer

ROOT = Path(__file__).resolve().parents[2]


def alias(package: dict) -> str:
    """Return a stable Bazel alias; borrow the package only for this call."""
    return (package["name"] + "_" + package["version"]).replace("-", "_").replace(".", "_").replace("+", "_")


def render(metadata: dict) -> dict[Path, str]:
    """Borrow Cargo metadata; return owned generated text without writing files."""
    packages = {p["id"]: p for p in metadata["packages"]}
    nodes = {n["id"]: n for n in metadata["resolve"]["nodes"]}
    direct = {
        edge["pkg"]
        for key, package in packages.items()
        if package["source"] is None
        for edge in nodes[key]["deps"]
    }
    registry = {key: p for key, p in packages.items() if key in direct and (p["source"] or "").startswith("registry+")}
    module = [
        "# Generated by build/bazel/sync-rust-deps.py; do not edit.\n",
        'crate = use_extension("@rules_rust//crate_universe:extensions.bzl", "crate")\n',
    ]
    for key, package in sorted(registry.items(), key=lambda item: alias(item[1])):
        values = {
            "package": package["name"],
            "package_alias": alias(package),
            "version": "=" + package["version"],
            "default_features": False,
            "features": sorted(nodes[key]["features"]),
        }
        module.append("crate.spec(" + ", ".join(name + " = " + repr(value) for name, value in values.items()) + ")\n")
    for package in sorted(packages.values(), key=lambda p: p["name"]):
        if package["source"] is None and package["name"] in ["aws-lc-rs", "aws-lc-sys"]:
            module.append("crate.spec(package = " + repr(package["name"]) + ", version = " + repr("=" + package["version"]) + ", default_features = False)\n")
    module.extend([
        'crate.annotation(crate = "aws-lc-rs", override_target_lib = "@origine//lib/aws-lc/aws-lc-rs:aws_lc_rs")\n',
        'crate.annotation(crate = "aws-lc-sys", override_target_lib = "@origine//lib/aws-lc/aws-lc-sys:aws_lc_sys")\n',
    ])
    module.extend([
        'crate.from_specs(name = "crates", cargo_lockfile = "//rust:Cargo.lock", supported_platform_triples = ["aarch64-apple-darwin"])\n',
        'use_repo(crate, "crates")\n',
    ])
    dependencies = {}
    features = {}
    for key, package in packages.items():
        if package["source"] is not None:
            continue
        features[package["name"]] = sorted(nodes[key]["features"])
        kinds = {}
        for edge in nodes[key]["deps"]:
            target = registry.get(edge["pkg"])
            if target is None:
                continue
            macro = any("proc-macro" in t["kind"] for t in target["targets"])
            for entry in edge["dep_kinds"]:
                kind = entry["kind"] or "normal"
                if macro:
                    kind = {"normal": "proc_macro", "dev": "proc_macro_dev", "build": "proc_macro_build"}[kind]
                kinds.setdefault(kind, set()).add("@crates//:" + alias(target))
        dependencies[package["name"]] = {k: sorted(v) for k, v in sorted(kinds.items())}
    bzl = [
        '"""Generated registry edges; local crate edges are explicit BUILD dependencies."""\n\n',
        "_DEPS = " + json.dumps(dict(sorted(dependencies.items())), indent=4) + "\n\n",
        'def registry_deps(package, kind = "normal"):\n',
        '    """Borrow names; return a fresh list of immutable dependency labels."""\n',
        '    return list(_DEPS[package].get(kind, []))\n',
        "\n_FEATURES = " + json.dumps(dict(sorted(features.items())), indent=4) + "\n\n",
        "def package_features(package):\n",
        '    """Borrow a name; return a fresh list of Cargo-resolved feature names."""\n',
        "    return list(_FEATURES[package])\n",
    ]
    return {
        ROOT / "build/bazel/rust-dependencies.MODULE.bazel": "".join(module),
        ROOT / "build/bazel/rust_dependencies.bzl": "".join(bzl),
    }


def main(
    check: Annotated[bool, typer.Option(help="Fail if generated Bazel dependencies have drifted.")] = False,
    metadata: Annotated[Path | None, typer.Option(help="Read previously captured cargo metadata JSON.")] = None,
) -> None:
    """Own generated outputs; borrow input files and Cargo's workspace read-only."""
    if metadata is None:
        result = subprocess.run(
            ["cargo", "metadata", "--locked", "--offline", "--all-features", "--filter-platform", "aarch64-apple-darwin", "--format-version", "1"],
            cwd=ROOT / "rust", check=True, capture_output=True, text=True,
        )
        data = json.loads(result.stdout)
    else:
        data = json.loads(metadata.read_text())
    for path, text in render(data).items():
        if check:
            if not path.exists() or path.read_text() != text:
                typer.echo(f"Stale: {path.relative_to(ROOT)}", err=True)
                raise typer.Exit(1)
        else:
            path.write_text(text)
            typer.echo(f"Updated {path.relative_to(ROOT)}")


if __name__ == "__main__":
    typer.run(main)
