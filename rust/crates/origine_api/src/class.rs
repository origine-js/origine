//! Rust-defined JS classes: the runtime half of `#[class]` (see `origine_api_macros`).
//!
//! A `#[class(path = "tls.RootPki", ..)]` impl block makes its Rust type a real JS class: one `FunctionTemplate`
//! per class and isolate (made on first use, never during a snapshot), named after the class, whose
//! constructor throws (`new RootPki()` is a `TypeError`: instances come from the named constructors), with
//! the static methods on the constructor, the methods and getters on the prototype (non-enumerable, like
//! `class` syntax), and instances made from its instance template, so `instanceof` works. Every instance
//! wraps its Rust value in the cppgc heap (`gc.rs`): the value is dropped when the object is collected.
//!
//! The brand check is the unwrap: a member called on anything that is not an instance of its class (another
//! class, a plain object, a subclass-less prototype) throws a `TypeError` ([`ClassError::Receiver`]), and an
//! argument typed `&T` rejects anything but a `T` (`argument N: expected a T`).
//!
//! The guest reaches a class through its installer, a native at the class's path (`native.tls.RootPki`): the
//! glue calls `native.tls.RootPki(failure, members?)` once per realm when the capability is bound. The
//! installer returns the constructor of the current realm after freezing it like the glue's own classes
//! (`freezeMethods` in `glue/util.js`: every method, accessor, the prototype and the constructor).
//! `failure` turns a native failure into the realm's error class instance (`glue/util.js` `hostError`); it is
//! kept for the realm, so the members of Rust classes, which the guest calls directly rather than through
//! the glue's `settling`, throw and reject the same `IoError`s as the natives. `members` are JS members the
//! glue defines on the prototype before it is frozen, for the few operations that need the glue's own
//! objects (an `api.net` socket, an `api.io` handle); a class is installed once per realm, so `members` after
//! the class was frozen is a `TypeError`.

use std::any::TypeId;
use std::cell::RefCell;
use std::fmt;

use origine_api_core::{ArgError, NativeError, errno};

use crate::FromJs;
use crate::gc;
use crate::native::{SideEffect, host_mut};

/// A Rust type that is a JS class. Implemented by `#[class]`; not meant to be written by hand.
pub trait Class: Sized + 'static {
    /// The JS class name (the last segment of the class's path).
    const NAME: &'static str;
    /// What an argument of this type expects, for `ArgError` (`a RootPki`, `an Identity`).
    const EXPECTED: &'static str;
    /// The class's statics, methods and getters.
    const MEMBERS: &'static [Member];
}

/// Where a member goes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum MemberKind {
    /// On the constructor (`RootPki.fromPem`).
    Static,
    /// On the prototype, called with an instance as `this`.
    Method,
    /// An accessor's get half on the prototype (read-only unless a `Setter` of the same name exists).
    Getter,
    /// An accessor's set half on the prototype, paired with the `Getter` of the same name.
    Setter,
}

/// One member of a class, generated by `#[class]`.
#[derive(Clone, Copy)]
pub struct Member {
    /// The JS name.
    pub name: &'static str,
    pub kind: MemberKind,
    /// The V8 function callback (a getter is a function too).
    pub callback: unsafe extern "C" fn(*const v8::FunctionCallbackInfo),
    pub side_effect: SideEffect,
    /// The function's `length`: the number of JS arguments.
    pub length: i32,
}

/// How the generated class code fails. Converted into a [`NativeError`] by [`From`]; the text is the
/// `Display` below.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ClassError {
    /// `new X()`: instances come from the class's named constructors.
    Construct { class: &'static str },
    /// A member called with a receiver that is not an instance of its class.
    Receiver { class: &'static str, member: &'static str },
    /// The installer was given JS members after the class was frozen in this realm.
    Frozen { class: &'static str },
    /// The isolate has no cppgc heap (V8 always makes one; this would be an embedding bug).
    NoHeap,
    /// V8 could not make the class's template, function or an instance (out of memory, or terminating).
    Unavailable { class: &'static str },
}

impl fmt::Display for ClassError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ClassError::Construct { class } => write!(f, "{class} has no public constructor: use its static methods"),
            ClassError::Receiver { class, member } => write!(f, "{class}.prototype.{member} called on an object that is not a {class}"),
            ClassError::Frozen { class } => write!(f, "{class} is already installed in this realm"),
            ClassError::NoHeap => f.write_str("the isolate has no cppgc heap"),
            ClassError::Unavailable { class } => write!(f, "cannot create {class}"),
        }
    }
}

impl std::error::Error for ClassError {}

impl From<ClassError> for NativeError {
    fn from(error: ClassError) -> NativeError {
        match error {
            ClassError::Construct { .. } | ClassError::Receiver { .. } | ClassError::Frozen { .. } => NativeError::Type(error.to_string()),
            ClassError::NoHeap | ClassError::Unavailable { .. } => NativeError::Error(error.to_string()),
        }
    }
}

/// A class value that `release()` can let go of before the object is collected: what was built from it holds
/// its own copy and keeps working; the instance itself answers `BadHandle` from then on.
pub struct Releasable<T>(RefCell<Option<T>>);

impl<T: Clone> Releasable<T> {
    pub fn new(value: T) -> Releasable<T> {
        Releasable(RefCell::new(Some(value)))
    }

    /// A copy of the value; `BadHandle` once released.
    pub fn get(&self) -> Result<T, NativeError> {
        self.0.borrow().clone().ok_or(NativeError::Errno(errno::BAD_HANDLE))
    }

    /// Drops the value now. Idempotent.
    pub fn release(&self) {
        // Taken out first: the value's `Drop` runs with no borrow held.
        let taken = self.0.borrow_mut().take();
        drop(taken);
    }
}

fn side_effect_type(side_effect: SideEffect) -> v8::SideEffectType {
    match side_effect {
        SideEffect::None => v8::SideEffectType::HasNoSideEffect,
        SideEffect::Receiver => v8::SideEffectType::HasSideEffectToReceiver,
        SideEffect::Any => v8::SideEffectType::HasSideEffect,
    }
}

fn string<'s>(scope: &mut v8::PinScope<'s, '_>, text: &str, class: &'static str) -> Result<v8::Local<'s, v8::String>, ClassError> {
    v8::String::new(scope, text).ok_or(ClassError::Unavailable { class })
}

/// The constructor callback: always throws.
///
/// # Safety
///
/// Only V8 may call this, as a function callback.
unsafe extern "C" fn construct<T: Class>(info: *const v8::FunctionCallbackInfo) {
    // SAFETY: forwarded from this function's contract.
    unsafe { crate::native::run_sync(info, |_, _| Err(ClassError::Construct { class: T::NAME }.into())) }
}

/// The name, getter and setter of one accessor.
type Accessor<'s> = (&'static str, Option<v8::Local<'s, v8::FunctionTemplate>>, Option<v8::Local<'s, v8::FunctionTemplate>>);

/// The template of `T` in this isolate, made on first use.
fn template<'s, T: Class>(scope: &mut v8::PinScope<'s, '_>) -> Result<v8::Local<'s, v8::FunctionTemplate>, NativeError> {
    if let Some(global) = host_mut(scope)?.classes.get(&TypeId::of::<T>()).cloned() {
        return Ok(v8::Local::new(scope, &global));
    }
    let template = v8::FunctionTemplate::builder_raw(construct::<T>).length(0).build(scope);
    let name = string(scope, T::NAME, T::NAME)?;
    template.set_class_name(name);
    template.read_only_prototype();
    let prototype = template.prototype_template(scope);
    // Accessors are set once per name, with both halves.
    let mut accessors: Vec<Accessor> = Vec::new();
    for member in T::MEMBERS {
        let key = string(scope, member.name, T::NAME)?;
        let function = v8::FunctionTemplate::builder_raw(member.callback)
            .constructor_behavior(v8::ConstructorBehavior::Throw)
            .side_effect_type(side_effect_type(member.side_effect))
            .length(member.length)
            .build(scope);
        match member.kind {
            MemberKind::Static => {
                function.set_class_name(key);
                template.set_with_attr(key.into(), function.into(), v8::PropertyAttribute::DONT_ENUM);
            }
            MemberKind::Method => {
                function.set_class_name(key);
                prototype.set_with_attr(key.into(), function.into(), v8::PropertyAttribute::DONT_ENUM);
            }
            MemberKind::Getter | MemberKind::Setter => {
                let getter = member.kind == MemberKind::Getter;
                let label = string(scope, &format!("{} {}", if getter { "get" } else { "set" }, member.name), T::NAME)?;
                function.set_class_name(label);
                let at = match accessors.iter().position(|(name, _, _)| *name == member.name) {
                    Some(at) => at,
                    None => {
                        accessors.push((member.name, None, None));
                        accessors.len() - 1
                    }
                };
                if getter {
                    accessors[at].1 = Some(function);
                } else {
                    accessors[at].2 = Some(function);
                }
            }
        }
    }
    for (name, getter, setter) in accessors {
        let key = string(scope, name, T::NAME)?;
        prototype.set_accessor_property(key.into(), getter, setter, v8::PropertyAttribute::DONT_ENUM);
    }
    let global = v8::Global::new(scope, template);
    host_mut(scope)?.classes.insert(TypeId::of::<T>(), global);
    Ok(template)
}

fn private<'s>(scope: &mut v8::PinScope<'s, '_>, name: &str) -> Result<v8::Local<'s, v8::Private>, ClassError> {
    let name = string(scope, name, "a class")?;
    Ok(v8::Private::for_api(scope, Some(name)))
}

/// Freezes every function and accessor among the own properties of `object`, then `object` itself (what
/// `freezeMethods` in `glue/util.js` does).
fn freeze_methods(scope: &mut v8::PinScope<'_, '_>, object: v8::Local<'_, v8::Object>, class: &'static str) -> Result<(), ClassError> {
    let unavailable = ClassError::Unavailable { class };
    let all = v8::GetPropertyNamesArgs {
        mode: v8::KeyCollectionMode::OwnOnly,
        property_filter: v8::PropertyFilter::ALL_PROPERTIES,
        index_filter: v8::IndexFilter::IncludeIndices,
        key_conversion: v8::KeyConversionMode::ConvertToString,
    };
    let keys = object.get_own_property_names(scope, all).ok_or(unavailable)?;
    let fields = [string(scope, "value", class)?, string(scope, "get", class)?, string(scope, "set", class)?];
    for at in 0..keys.length() {
        let key = keys.get_index(scope, at).ok_or(unavailable)?;
        let key = v8::Local::<v8::Name>::try_from(key).map_err(|_| unavailable)?;
        let descriptor = object.get_own_property_descriptor(scope, key).ok_or(unavailable)?;
        let Ok(descriptor) = v8::Local::<v8::Object>::try_from(descriptor) else { continue };
        for field in fields {
            let part = descriptor.get(scope, field.into()).ok_or(unavailable)?;
            if let Ok(function) = v8::Local::<v8::Function>::try_from(part) {
                function.set_integrity_level(scope, v8::IntegrityLevel::Frozen);
            }
        }
    }
    object.set_integrity_level(scope, v8::IntegrityLevel::Frozen);
    Ok(())
}

/// Copies the own properties of `members` onto `prototype` as non-enumerable members.
fn define_members(
    scope: &mut v8::PinScope<'_, '_>,
    prototype: v8::Local<'_, v8::Object>,
    members: v8::Local<'_, v8::Object>,
    class: &'static str,
) -> Result<(), ClassError> {
    let unavailable = ClassError::Unavailable { class };
    let all = v8::GetPropertyNamesArgs {
        mode: v8::KeyCollectionMode::OwnOnly,
        property_filter: v8::PropertyFilter::ALL_PROPERTIES,
        index_filter: v8::IndexFilter::IncludeIndices,
        key_conversion: v8::KeyConversionMode::ConvertToString,
    };
    let keys = members.get_own_property_names(scope, all).ok_or(unavailable)?;
    let (value_key, get_key, set_key) = (string(scope, "value", class)?, string(scope, "get", class)?, string(scope, "set", class)?);
    for at in 0..keys.length() {
        let key = keys.get_index(scope, at).ok_or(unavailable)?;
        let key = v8::Local::<v8::Name>::try_from(key).map_err(|_| unavailable)?;
        let descriptor = members.get_own_property_descriptor(scope, key).ok_or(unavailable)?;
        let Ok(descriptor) = v8::Local::<v8::Object>::try_from(descriptor) else { continue };
        let mut definition = if descriptor.has_own_property(scope, value_key.into()).unwrap_or(false) {
            let value = descriptor.get(scope, value_key.into()).ok_or(unavailable)?;
            v8::PropertyDescriptor::new_from_value_writable(value, true)
        } else {
            let get = descriptor.get(scope, get_key.into()).ok_or(unavailable)?;
            let set = descriptor.get(scope, set_key.into()).ok_or(unavailable)?;
            v8::PropertyDescriptor::new_from_get_set(get, set)
        };
        definition.set_enumerable(false);
        definition.set_configurable(true);
        if prototype.define_property(scope, key, &definition) != Some(true) {
            return Err(unavailable);
        }
    }
    Ok(())
}

/// The constructor of `T` in the current realm, frozen (with `members` defined on its prototype first when
/// this is the first time in this realm).
fn function<'s, T: Class>(
    scope: &mut v8::PinScope<'s, '_>,
    members: Option<v8::Local<'s, v8::Object>>,
) -> Result<v8::Local<'s, v8::Function>, NativeError> {
    let unavailable = ClassError::Unavailable { class: T::NAME };
    let template = template::<T>(scope)?;
    let function = template.get_function(scope).ok_or(unavailable)?;
    let sealed = private(scope, "origine:class.sealed")?;
    if function.get_private(scope, sealed).is_some_and(|flag| flag.is_true()) {
        return match members {
            Some(_) => Err(ClassError::Frozen { class: T::NAME }.into()),
            None => Ok(function),
        };
    }
    let key = string(scope, "prototype", T::NAME)?;
    let prototype = function.get(scope, key.into()).and_then(|p| v8::Local::<v8::Object>::try_from(p).ok()).ok_or(unavailable)?;
    if let Some(members) = members {
        define_members(scope, prototype, members, T::NAME)?;
    }
    let yes = v8::Boolean::new(scope, true);
    function.set_private(scope, sealed, yes.into());
    freeze_methods(scope, prototype, T::NAME)?;
    freeze_methods(scope, function.into(), T::NAME)?;
    Ok(function)
}

/// Wraps `value` in a new instance of its class in the current realm (`IntoJs` of a `#[class]` type).
pub fn wrap<'s, T: Class>(scope: &mut v8::PinScope<'s, '_>, value: T) -> Result<v8::Local<'s, v8::Value>, NativeError> {
    // Instantiating the constructor first makes sure the realm's class is frozen before an instance escapes.
    function::<T>(scope, None)?;
    let template = template::<T>(scope)?;
    let object = template.instance_template(scope).new_instance(scope).ok_or(ClassError::Unavailable { class: T::NAME })?;
    gc::attach(scope, object, value)?;
    Ok(object.into())
}

/// The instance `this` of a member call, borrowed for the call; [`ClassError::Receiver`] for anything else.
pub fn receiver<'s, T: Class>(
    scope: &mut v8::PinScope<'s, '_>,
    args: &v8::FunctionCallbackArguments<'s>,
    member: &'static str,
) -> Result<&'s T, ClassError> {
    let this: v8::Local<'s, v8::Value> = args.this().into();
    let isolate: &mut v8::Isolate = scope;
    gc::unwrap_ref::<T>(isolate, this).ok_or(ClassError::Receiver { class: T::NAME, member })
}

/// An instance of a class as an argument, borrowed for the call. An async native clones what it keeps.
impl<'s, T: Class> FromJs<'s> for &'s T {
    fn from_js(scope: &mut v8::PinScope<'s, '_>, value: v8::Local<'s, v8::Value>, index: usize) -> Result<Self, ArgError> {
        let isolate: &mut v8::Isolate = scope;
        gc::unwrap_ref::<T>(isolate, value).ok_or_else(|| ArgError::new(index, T::EXPECTED))
    }
}

/// The installer native of `T` (`native.<ns>.<Class>(failure, members?)`), see the module docs.
///
/// # Safety
///
/// Only V8 may call this, as a function callback.
pub unsafe extern "C" fn install<T: Class>(info: *const v8::FunctionCallbackInfo) {
    // SAFETY: forwarded from this function's contract.
    unsafe {
        crate::native::run_sync(info, |scope, args| {
            let failure: v8::Local<v8::Function> = FromJs::from_js(scope, args.get(0), 0)?;
            let members: Option<v8::Local<v8::Object>> = FromJs::from_js(scope, args.get(1), 1)?;
            let key = private(scope, FAILURE)?;
            let global = scope.get_current_context().global(scope);
            global.set_private(scope, key, failure.into());
            function::<T>(scope, members).map(Into::into)
        })
    }
}

/// The private the realm's failure converter is kept under, on the realm's global object.
const FAILURE: &str = "origine:class.failure";

/// `error` as the guest sees it in the current realm: the realm's error class instance when an installer
/// registered the converter (errno failures only), else the plain value of `native::error_value`.
pub(crate) fn guest_error<'s>(scope: &mut v8::PinScope<'s, '_>, error: NativeError) -> v8::Local<'s, v8::Value> {
    let errno = error.code().is_some();
    let value = crate::native::error_value(scope, error);
    if !errno {
        return value;
    }
    let Ok(key) = private(scope, FAILURE) else { return value };
    let global = scope.get_current_context().global(scope);
    let Some(failure) = global.get_private(scope, key).and_then(|f| v8::Local::<v8::Function>::try_from(f).ok()) else {
        return value;
    };
    let undefined = v8::undefined(scope).into();
    failure.call(scope, undefined, &[value]).unwrap_or(value)
}
