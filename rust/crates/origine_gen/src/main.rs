//! Generators for the cross-language contracts (docs/contracts.md): the Rust bindings of the C headers.
//!
//! CONTRACT: docs/contracts.md surfaces A, B, C and E. The header is the source of truth; run
//! `just gen-contracts` after changing it (`just check-contracts` fails when the committed file
//! is stale). Needs libclang (LIBCLANG_PATH).
//!
//! usage: cargo run -p origine_gen -- io-sys <src/io/include/origine_io.h> <sys_gen.rs>
//!        cargo run -p origine_gen -- oxc-abi <origine_oxc.h> <header_abi.rs>
use bindgen::callbacks::{IntKind, ParseCallbacks};
use bindgen::{EnumVariation, MacroTypeVariation};
use std::collections::HashSet;

/// Types the integer macros: `...ull` in the header means u64, `OIO_FDCWD` is an `oio_fd`.
#[derive(Debug)]
struct Macros {
    wide: HashSet<String>,
}

impl ParseCallbacks for Macros {
    fn int_macro(&self, name: &str, _value: i64) -> Option<IntKind> {
        if name == "OIO_FDCWD" {
            Some(IntKind::Custom { name: "oio_fd", is_signed: true })
        } else if self.wide.contains(name) {
            Some(IntKind::U64)
        } else {
            None
        }
    }
}

/// Names of the `#define`s whose replacement text contains a `ull` literal suffix.
fn wide_macros(header: &str) -> HashSet<String> {
    let mut out = HashSet::new();
    for line in header.lines() {
        let Some(rest) = line.strip_prefix("#define ") else { continue };
        let mut parts = rest.splitn(2, char::is_whitespace);
        let (Some(name), Some(value)) = (parts.next(), parts.next()) else { continue };
        if value.contains("ull") {
            out.insert(name.to_owned());
        }
    }
    out
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.iter().map(String::as_str).collect::<Vec<_>>().as_slice() {
        ["io-sys", header, output] => io_sys(header, output),
        ["oxc-abi", header, output] => oxc_abi(header, output),
        ["api-abi", header, output] => api_abi(header, output),
        _ => panic!("usage: origine_gen io-sys|oxc-abi|api-abi <header> <output>"),
    }
}

fn io_sys(header: &str, output: &str) {
    let text = std::fs::read_to_string(header).expect("read header");
    let bindings = bindgen::Builder::default()
        .header(header)
        .parse_callbacks(Box::new(Macros { wide: wide_macros(&text) }))
        .allowlist_function("oio_.*")
        .allowlist_type("oio_.*")
        .allowlist_var("OIO_.*")
        .default_enum_style(EnumVariation::Consts)
        .prepend_enum_name(false)
        .default_macro_constant_type(MacroTypeVariation::Unsigned)
        // LP64 size asserts would break 32-bit hosts; the Zig side checks the layout (c_api.zig).
        .layout_tests(false)
        .derive_default(true)
        .derive_debug(true)
        .use_core()
        .generate_comments(false)
        .generate()
        .expect("bindgen failed");
    let mut code = bindings.to_string();
    // bindgen types C enums as unsigned; the header uses them as `int32_t kind` and `int mode`, so
    // the Rust constants take those types.
    for (from, to) in [
        ("pub type oio_kind = ::core::ffi::c_uint;", "pub type oio_kind = i32;"),
        ("pub type oio_run_mode = ::core::ffi::c_uint;", "pub type oio_run_mode = ::core::ffi::c_int;"),
    ] {
        assert!(code.contains(from), "bindgen output changed: {from}");
        code = code.replace(from, to);
    }
    // The list of every function, for the Miri fake (`mock.rs`): it must define each one with the
    // same signature (see `sys.rs`).
    let fns: Vec<&str> = code.lines().filter_map(|l| l.trim_start().strip_prefix("pub fn ")).filter_map(|l| l.split('(').next()).collect();
    assert!(fns.len() > 30 && fns.iter().all(|f| f.starts_with("oio_")), "unexpected bindgen output: {fns:?}");
    let list = fns.iter().map(|f| format!("        {f},\n")).collect::<String>();
    code.push_str(&format!("\n/// Calls `$m!` with the name of every `oio_*` function of the header.\nmacro_rules! for_each_oio_fn {{\n    ($m:ident) => {{\n        $m! {{\n{list}        }}\n    }};\n}}\n"));
    let banner = "// @generated by rust/crates/origine_io/crates/origine_gen from src/io/include/origine_io.h; do not edit.\n// Regenerate with `just gen-contracts` (docs/contracts.md, surface A).\n";
    std::fs::write(output, format!("{banner}{code}")).expect("write output");
}

/// `origine_oxc/src/header_abi.rs`: the header as Rust sees it, for compile-time checks in
/// `origine_oxc/src/lib.rs`. Two passes: `c_view` holds the C structs under their own names (for
/// layout and field comparison with the hand-written `#[repr(C)]` structs), the top level holds the
/// constants and extern functions typed with the crate's own structs, so that the Rust
/// definitions can be compared to them as fn pointers.
fn oxc_abi(header: &str, output: &str) {
    let base = || {
        bindgen::Builder::default()
            .header(header)
            .allowlist_function("origine_oxc_.*")
            .allowlist_type("Oxc.*")
            .allowlist_var("ORIGINE_OXC_.*")
            .default_enum_style(EnumVariation::Consts)
            .default_macro_constant_type(MacroTypeVariation::Unsigned)
            .layout_tests(false)
            .derive_default(false)
            .use_core()
            .generate_comments(false)
    };
    let view = base().generate().expect("bindgen failed").to_string();
    let api = base()
        .blocklist_type("OxcOptions")
        .blocklist_type("OxcResult")
        .raw_line("use crate::{OxcOptions, OxcResult};")
        .generate()
        .expect("bindgen failed")
        .to_string();
    let banner = "// @generated by rust/crates/origine_gen from include/origine_oxc.h; do not edit.\n// Regenerate with `just gen-contracts` (docs/contracts.md, surface E).\n";
    let indented: String = view.lines().map(|l| format!("    {l}\n")).collect();
    let text = format!("{banner}{api}\n/// The C structs, under the names of the header.\npub mod c_view {{\n{indented}}}\n");
    std::fs::write(output, text).expect("write output");
}

/// `origine_api/src/abi_gen.rs`: structs, constants and extern declarations of `origine_api.h`.
/// The crate uses the structs directly and compares its own `extern "C"` definitions with the
/// declarations as fn pointers (see `origine_api/src/lib.rs`).
fn api_abi(header: &str, output: &str) {
    let bindings = bindgen::Builder::default()
        .header(header)
        .allowlist_function("origine_api_.*")
        .allowlist_type("origine_api_.*")
        .allowlist_var("ORIGINE_API_.*")
        .default_enum_style(EnumVariation::Consts)
        .prepend_enum_name(false)
        .default_macro_constant_type(MacroTypeVariation::Unsigned)
        .layout_tests(false)
        .derive_default(true)
        .derive_debug(true)
        .use_core()
        .generate_comments(false)
        .generate()
        .expect("bindgen failed");
    let mut code = bindings.to_string();
    // The header uses the enums as `uint32_t` fields.
    for name in ["origine_api_side_effect", "origine_api_needs"] {
        let from = format!("pub type {name} = ::core::ffi::c_uint;");
        assert!(code.contains(&from), "bindgen output changed: {from}");
        code = code.replace(&from, &format!("pub type {name} = u32;"));
    }
    let banner = "// @generated by rust/crates/origine_gen from include/origine_api.h; do not edit.\n// Regenerate with `just gen-contracts` (docs/contracts.md, surfaces B and C).\n";
    std::fs::write(output, format!("{banner}{code}")).expect("write output");
}
