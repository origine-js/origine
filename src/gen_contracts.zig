//! Generates the committed files of the cross-language contracts that come from Zig.
//! CONTRACT: docs/contracts.md (surface D). Run through `just gen-contracts`:
//!
//!     zig run src/gen_contracts.zig -- <repo root>
//!
//! Also `src/api/api_abi_check.c` from src/api/api_abi.zig (checked against origine_api.h the same way).
//! Writes `rust/crates/origine_api_core/src/errno_table.rs` from `Errno` (src/api/errno_codes.zig)
//! and `src/api/transform/oxc_abi_check.c` from the oxc ABI declarations (src/api/transform/oxc_abi.zig:
//! a C file whose static assertions and prototypes `just check-contracts` compiles against
//! rust/crates/origine_oxc/include/origine_oxc.h).
//! Also `src/repl/repl_abi_check.c` from src/repl/repl_abi.zig, against origine_repl.h (surface G).
//! Also `types/generated/errno.d.ts` (the TypeScript error names and codes of `@origine/types`) from
//! `Errno`, with its `///` doc comments as JSDoc.
//! `just check-contracts` regenerates into a temp copy and fails on any difference.
const std = @import("std");
const codes = @import("api/errno_codes.zig");
const IoErrno = codes.IoErrno;
const HostErrno = codes.HostErrno;
const oxc = @import("api/transform/oxc_abi.zig");
const api = @import("api/api_abi.zig");
const repl = @import("repl/repl_abi.zig");

pub fn main(init: std.process.Init) !void {
    const alloc = init.gpa;
    const args = try init.minimal.args.toSlice(alloc);
    defer alloc.free(args);
    if (args.len != 2) return error.UsageRepoRoot;
    const root = try std.Io.Dir.cwd().openDir(init.io, args[1], .{});
    defer root.close(init.io);

    var out: std.Io.Writer.Allocating = .init(alloc);
    defer out.deinit();
    try errnoTable(&out.writer);
    try root.writeFile(init.io, .{ .sub_path = "rust/crates/origine_api_core/src/errno_table.rs", .data = out.written() });

    out.clearRetainingCapacity();
    try errnoTypes(&out.writer);
    try root.writeFile(init.io, .{ .sub_path = "types/generated/errno.d.ts", .data = out.written() });

    out.clearRetainingCapacity();
    try oxcAbiCheck(&out.writer);
    try root.writeFile(init.io, .{ .sub_path = "src/api/transform/oxc_abi_check.c", .data = out.written() });

    out.clearRetainingCapacity();
    try replAbiCheck(&out.writer);
    try root.writeFile(init.io, .{ .sub_path = "src/repl/repl_abi_check.c", .data = out.written() });

    out.clearRetainingCapacity();
    try apiAbiCheck(&out.writer);
    try root.writeFile(init.io, .{ .sub_path = "src/api/api_abi_check.c", .data = out.written() });
}

/// `FileNotFound` -> `FILE_NOT_FOUND`.
fn screamingSnake(w: *std.Io.Writer, name: []const u8) !void {
    for (name, 0..) |c, i| {
        if (std.ascii.isUpper(c) and i != 0) try w.writeByte('_');
        try w.writeByte(std.ascii.toUpper(c));
    }
}

fn errnoTable(w: *std.Io.Writer) !void {
    try w.writeAll(
        \\// @generated by src/gen_contracts.zig from `IoErrno` and `HostErrno` in src/api/errno_codes.zig; do not edit.
        \\// Regenerate with `just gen-contracts` (docs/contracts.md, surface D).
        \\
        \\
    );
    try w.writeAll("// Host domain: origine's own runtime concepts.\n");
    for (std.enums.values(HostErrno)) |tag| try constant(w, @tagName(tag), @backingInt(tag));
    try w.writeAll("\n// I/O domain: Rust's `std::io::ErrorKind` names, plus `TooManyOpenFiles` and `Io`.\n");
    for (std.enums.values(IoErrno)) |tag| try constant(w, @tagName(tag), @backingInt(tag));
    try w.writeAll(
        \\
        \\/// The host domain with its guest-visible names, ascending.
        \\#[rustfmt::skip]
        \\pub const HOST_CODES: &[(u32, &str)] = &[
        \\
    );
    for (std.enums.values(HostErrno)) |tag| try entry(w, @tagName(tag));
    try w.writeAll(
        \\];
        \\
        \\/// The I/O domain with its guest-visible names, ascending.
        \\pub const IO_CODES: &[(u32, &str)] = &[
        \\
    );
    for (std.enums.values(IoErrno)) |tag| try entry(w, @tagName(tag));
    try w.writeAll(
        \\];
        \\
        \\/// Every code with its guest-visible name, ascending (`HOST_CODES` then `IO_CODES`).
        \\pub const ALL: [(u32, &str); HOST_CODES.len() + IO_CODES.len()] = {
        \\    let mut all = [(0, ""); HOST_CODES.len() + IO_CODES.len()];
        \\    let mut i = 0;
        \\    while i < HOST_CODES.len() {
        \\        all[i] = HOST_CODES[i];
        \\        i += 1;
        \\    }
        \\    while i < HOST_CODES.len() + IO_CODES.len() {
        \\        all[i] = IO_CODES[i - HOST_CODES.len()];
        \\        i += 1;
        \\    }
        \\    all
        \\};
        \\
        \\/// Whether `code` is in the host domain (`false` for I/O codes and unknown ones).
        \\pub fn is_host(code: u32) -> bool {
        \\    matches!(code,
    );
    var first = true;
    for (std.enums.values(HostErrno)) |tag| {
        try w.writeAll(if (first) " " else " | ");
        first = false;
        try screamingSnake(w, @tagName(tag));
    }
    try w.writeAll(
        \\)
        \\}
        \\
        \\/// The guest-visible name of `code` (`native.errors` / `origine:@std/errno`); unknown codes are
        \\/// `Unexpected`.
        \\pub fn name_of(code: u32) -> &'static str {
        \\    match code {
        \\
    );
    inline for (.{ HostErrno, IoErrno }) |E| {
        inline for (std.enums.values(E)) |tag| {
            if (comptime std.mem.eql(u8, @tagName(tag), "Unexpected")) continue;
            const name = @tagName(tag);
            try w.writeAll("        ");
            try screamingSnake(w, name);
            try w.print(" => \"{s}\",\n", .{name});
        }
    }
    try w.writeAll(
        \\        _ => "Unexpected",
        \\    }
        \\}
        \\
    );
}

fn constant(w: *std.Io.Writer, name: []const u8, value: u32) !void {
    try w.writeAll("pub const ");
    try screamingSnake(w, name);
    try w.print(": u32 = {d};\n", .{value});
}

fn entry(w: *std.Io.Writer, name: []const u8) !void {
    try w.writeAll("    (");
    try screamingSnake(w, name);
    try w.print(", \"{s}\"),\n", .{name});
}

const errno_source = @embedFile("api/errno_codes.zig");

/// The `///` lines directly above the enum member `name` in errno_codes.zig, joined with spaces
/// (empty when the member has none).
fn memberDoc(buf: []u8, name: []const u8) []const u8 {
    var len: usize = 0;
    var doc_lines: usize = 0;
    var lines = std.mem.splitScalar(u8, errno_source, '\n');
    var pending: [8][]const u8 = undefined;
    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t");
        if (std.mem.startsWith(u8, line, "/// ") or std.mem.eql(u8, line, "///")) {
            if (doc_lines < pending.len) pending[doc_lines] = std.mem.trim(u8, line[3..], " ");
            doc_lines += 1;
            continue;
        }
        if (std.mem.startsWith(u8, line, name) and line.len > name.len and std.mem.startsWith(u8, line[name.len..], " = ")) {
            for (pending[0..@min(doc_lines, pending.len)]) |part| {
                if (len != 0) {
                    buf[len] = ' ';
                    len += 1;
                }
                @memcpy(buf[len..][0..part.len], part);
                len += part.len;
            }
            return buf[0..len];
        }
        doc_lines = 0;
    }
    return buf[0..0];
}

/// `types/generated/errno.d.ts`: the error names and codes as TypeScript types.
fn errnoTypes(w: *std.Io.Writer) !void {
    try w.writeAll(
        \\// @generated by src/gen_contracts.zig from `IoErrno` and `HostErrno` in src/api/errno_codes.zig; do not edit.
        \\// Regenerate with `just gen-contracts` (docs/contracts.md, surface D).
        \\
        \\
    );
    inline for (.{ .{ "Io", IoErrno, "What Rust's `std::io::ErrorKind` names (plus `TooManyOpenFiles` and `Io`): raised by fs and net. Names are Rust's." }, .{ "Host", HostErrno, "origine's own runtime concepts, which Rust's `ErrorKind` has no name for: raised by any native." } }) |dom| {
        try w.print("/** {s} */\nexport interface {s}ErrnoTable {{\n", .{ dom[2], dom[0] });
        var buf: [512]u8 = undefined;
        for (std.enums.values(dom[1])) |tag| {
            const name = @tagName(tag);
            const doc = memberDoc(&buf, name);
            if (doc.len != 0) try w.print("  /** {s} */\n", .{doc});
            try w.print("  readonly {s}: {d};\n", .{ name, @backingInt(tag) });
        }
        try w.print(
            \\}}
            \\
            \\/** Name of a {0s} error code, e.g. `'{1s}'`. */
            \\export type {0s}ErrnoName = keyof {0s}ErrnoTable;
            \\
            \\/** A code of a {0s} error, e.g. `{2d}`. */
            \\export type {0s}ErrnoCode = {0s}ErrnoTable[{0s}ErrnoName];
            \\
            \\
        , .{ dom[0], @tagName(std.enums.values(dom[1])[0]), @backingInt(std.enums.values(dom[1])[0]) });
    }
    try w.writeAll(
        \\/**
        \\ * Both tables, by domain (`origine:@std/errno`'s `ERRNO`). The domain and category of a code are
        \\ * readable from its number (src/api/errno_codes.zig); look codes up by name, the numbers are not guaranteed stable yet.
        \\ */
        \\export interface ErrnoTable {
        \\  readonly io: IoErrnoTable;
        \\  readonly host: HostErrnoTable;
        \\}
        \\
    );
}

/// The C spelling of an ABI type used by `oxc_abi.zig`.
fn cType(comptime T: type) []const u8 {
    return switch (T) {
        void => "void",
        u32 => "uint32_t",
        usize => "size_t",
        ?[*]const u8 => "const uint8_t *",
        *oxc.CResult => "OxcResult *",
        ?*const oxc.COptions => "const OxcOptions *",
        bool => "bool",
        u8 => "uint8_t",
        i32 => "int32_t",
        i64 => "int64_t",
        c_int => "int",
        *anyopaque, ?*anyopaque => "void *",
        *repl.Repl, ?*repl.Repl => "OrigineRepl *",
        *const repl.Repl => "const OrigineRepl *",
        *repl.Sink => "OrigineReplSink *",
        ?*const repl.Host => "const OrigineReplHost *",
        repl.CompleteFn => "bool (*)(void *, const uint8_t *, size_t, OrigineReplSink *)",
        ?*usize => "size_t *",
        *const api.OriginCfg => "const origine_api_cfg *",
        *api.Native => "origine_api_native *",
        api.Callback => "void (*)(const void *)",
        [*:0]const u8 => "const char *",
        else => @compileError("gen_contracts: no C spelling for " ++ @typeName(T)),
    };
}

fn cStruct(w: *std.Io.Writer, comptime T: type, c_name: []const u8) !void {
    try w.print("_Static_assert(sizeof({s}) == {d}, \"{s}: size\");\n", .{ c_name, @sizeOf(T), c_name });
    inline for (@typeInfo(T).@"struct".field_names) |name| {
        const F = @FieldType(T, name);
        try w.print("_Static_assert(offsetof({s}, {s}) == {d}, \"{s}.{s}: offset\");\n", .{ c_name, name, @offsetOf(T, name), c_name, name });
        try w.print("_Static_assert(_Generic(((({s} *)0)->{s}), {s}: 1, default: 0), \"{s}.{s}: type\");\n", .{ c_name, name, cType(F), c_name, name });
    }
}

fn cProto(w: *std.Io.Writer, comptime name: []const u8, comptime f: anytype) !void {
    const info = @typeInfo(@TypeOf(f)).@"fn";
    try w.print("{s} {s}(", .{ cType(info.return_type.?), name });
    if (info.param_types.len == 0) try w.writeAll("void");
    inline for (info.param_types, 0..) |P, i| {
        if (i != 0) try w.writeAll(", ");
        try w.writeAll(cType(P.?));
    }
    try w.writeAll(");\n");
}

