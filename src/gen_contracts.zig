fn cEnum(w: *std.Io.Writer, comptime E: type, prefix: []const u8) !void {
    for (std.enums.values(E)) |tag| {
        try w.print("_Static_assert({s}", .{prefix});
        for (@tagName(tag)) |c| try w.writeByte(std.ascii.toUpper(c));
        try w.print(" == {d}, \"{s}\");\n", .{ @backingInt(tag), prefix });
    }
}

