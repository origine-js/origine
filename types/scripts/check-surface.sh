#!/bin/sh
# Fails when the runtime has a public name the declarations lack. It cannot prove the signatures
# right (the type tests and review do that); it catches a name added to the JS and forgotten here.
#
# Compared: the exports of each std module (src/js/std/*.js) with the `declare module` file, the
# methods of Dir/File and the keys of `ops` (std/io.js), the fs operation names (glue/fs.js), the
# members of the net classes (glue/net.js), and the keys of the api.* capabilities.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
js=$here/../src/js
status=0

# missing <what> <declaration file> <name>...: report each name not mentioned as a whole word.
missing() {
    what=$1 file=$2
    shift 2
    for name in "$@"; do
        if ! rg -qw -- "$name" "$file"; then
            echo "check-types: $what: '$name' is in the runtime but not declared in ${file#"$here"/}" >&2
            status=1
        fi
    done
}

exports_of() { rg -o '^export (const|function|class|async function) (\w+)' -r '$2' "$1"; }

for pair in io:io fs:fs text:text quansync:quansync errno:errno; do
    mod=${pair%%:*} decl=${pair##*:}
    src=$js/std/$mod.js
    [ -f "$src" ] || continue
    # shellcheck disable=SC2046
    missing "origine:@std/$mod export" "$here/std/$decl.d.ts" $(exports_of "$src")
done
# errno is generated by the engine, not a JS file.
missing "origine:@std/errno export" "$here/std/errno.d.ts" ERRNO
missing "origine:@std/transformer/oxc export" "$here/std/transformer-oxc.d.ts" $(exports_of "$js/std/transformer/oxc.js")

# Dir / File methods and the `ops` object.
methods() { awk -v cls="$2" '$0 ~ "^class "cls" " {on=1; next} on && /^}/ {exit} on' "$1" | rg -o '^  ([a-zA-Z]\w*)\(' -r '$1' | rg -v '^constructor$'; }
# shellcheck disable=SC2046
missing "Dir method" "$here/std/io.d.ts" $(methods "$js/std/io.js" DirImpl)
# shellcheck disable=SC2046
missing "File method" "$here/std/io.d.ts" $(methods "$js/std/io.js" FileImpl)
# shellcheck disable=SC2046
missing "ops key" "$here/std/io.d.ts" $(awk '/^export const ops = freeze\(\{/ {on=1; next} on && /^\}\);/ {exit} on' "$js/std/io.js" | rg -o '^  (\w+)' -r '$1')

# The operation names of the fs grants.
# shellcheck disable=SC2046
missing "fs operation" "$here/fs.d.ts" $(rg -o '^      ((dir|file)[A-Z]\w*)\(' -r '$1' "$js/glue/fs.js" | sort -u)

# The members of the net classes and the cap.
# shellcheck disable=SC2046
missing "net member" "$here/net.d.ts" $(awk '/Base of every handle/ {on=1} /const makeSocket/ {on=0} on' "$js/glue/net.js" | rg -o '^    (?:get |set |static )?([a-zA-Z]\w*)\(' -r '$1' | rg -v '^(constructor|if|for|while|switch|catch|return)$' | sort -u)
# shellcheck disable=SC2046
missing "net cap member" "$here/net.d.ts" listen connect Handle Server PullServer EventServer Socket PullSocket EventSocket

# Capabilities of api.*.
missing "api capability" "$here/api.d.ts" fs env scope io net
missing "env member" "$here/env.d.ts" args get list narrow
missing "io cap member" "$here/io.d.ts" create narrow close run now timer timerAt sleep sleepUntil
missing "scope option" "$here/scope.d.ts" main importMap loader preload transformers origineNamespace run close create

exit $status
